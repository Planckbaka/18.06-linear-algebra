export function getModuleById(moduleId: string): CourseModule {
  const mod = COURSE_MODULES.find((m) => m.id === moduleId);
  if (!mod) throw new Error(`Unknown module: ${moduleId}`);
  return mod;
}

export function getSessionBySlug(slug: string): LectureSession | undefined {
  return LECTURE_SESSIONS.find((s) => s.slug === slug);
}

export function getAdjacentSessions(slug: string): {
  prev?: LectureSession;
  next?: LectureSession;
} {
  const idx = LECTURE_SESSIONS.findIndex((s) => s.slug === slug);
  if (idx === -1) return {};
  return {
    prev: idx > 0 ? LECTURE_SESSIONS[idx - 1] : undefined,
    next: idx < LECTURE_SESSIONS.length - 1 ? LECTURE_SESSIONS[idx + 1] : undefined,
  };
}

export function getAllAIBridges(): Array<{
  session: LectureSession;
  bridge: FrontierAIBridgeMeta;
}> {
  return LECTURE_SESSIONS.filter(
    (s): s is LectureSession & { aiBridge: FrontierAIBridgeMeta } => Boolean(s.aiBridge)
  ).map((session) => ({
    session,
    bridge: session.aiBridge,
  }));
}
